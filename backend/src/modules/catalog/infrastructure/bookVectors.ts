import { embedder as defaultEmbedder } from "../../../infrastructure/embedder";
import { sql } from "../../../infrastructure/postgres";
import type { Embedder } from "../../../shared/Embedder";
import type { CatalogIntegration } from "../domain/CatalogIntegration";

const TABLE = "livros_vetores";
const INDEX = "livros_vetores_embedding_idx";

export type IndexResult = {
  indexed: number;
  removed: number;
};

export type KnnHit = {
  id: number;
  distance: number;
};

/** The text used to generate each book's embedding. */
function indexText(title: string, authorName: string | undefined): string {
  return authorName ? `${title} — ${authorName}` : title;
}

/** Converts a Float32Array to pgvector's textual representation. */
function vectorToText(vector: Float32Array): string {
  return `[${Array.from(vector).join(",")}]`;
}

/**
 * Ensures that the vector table and HNSW index exist for this embedder.
 *
 * Returns true when the table had to be created or recreated.
 */
export async function ensureBookIndex(embedder: Embedder): Promise<boolean> {
  const dimensions = embedder.dimensions;

  if (
    !Number.isInteger(dimensions) ||
    dimensions < 1 ||
    dimensions > 2000
  ) {
    throw new Error(`Invalid embedding dimensions: ${dimensions}`);
  }

  const [existing] = await sql`
    SELECT
      obj_description(c.oid, 'pg_class') AS model,
      format_type(a.atttypid, a.atttypmod) AS vector_type
    FROM pg_class c
    LEFT JOIN pg_attribute a
      ON a.attrelid = c.oid
      AND a.attname = 'embedding'
    WHERE c.oid = to_regclass(${TABLE})
  ` as {
    model: string | null;
    vector_type: string | null;
  }[];

  const expectedType = `vector(${dimensions})`;

  if (
    existing?.model === embedder.id &&
    existing.vector_type === expectedType
  ) {
    await sql.unsafe(`
      CREATE INDEX IF NOT EXISTS ${INDEX}
      ON ${TABLE}
      USING hnsw (embedding vector_cosine_ops)
    `);

    return false;
  }

  // Vectors generated by another model cannot be compared with this model.
  await sql.unsafe(`DROP TABLE IF EXISTS ${TABLE}`);

  await sql.unsafe(`
    CREATE TABLE ${TABLE} (
      livro_id INTEGER PRIMARY KEY
        REFERENCES livros(id) ON DELETE CASCADE,
      texto TEXT NOT NULL,
      embedding vector(${dimensions}) NOT NULL
    )
  `);

  await sql.unsafe(`
    CREATE INDEX ${INDEX}
    ON ${TABLE}
    USING hnsw (embedding vector_cosine_ops)
  `);

  // Store the embedder ID in the table comment.
  const model = embedder.id.replaceAll("'", "''");

  await sql.unsafe(`
    COMMENT ON TABLE ${TABLE} IS '${model}'
  `);

  return true;
}

/**
 * Synchronizes the specified books with PostgreSQL.
 *
 * Only books whose indexed text has changed or that do not have
 * a stored vector are embedded again.
 */
async function syncIds(
  ids: number[],
  integration: CatalogIntegration,
  embedder: Embedder | null,
): Promise<IndexResult & { created: boolean }> {
  const result = {
    indexed: 0,
    removed: 0,
    created: false,
  };

  const unique = [...new Set(ids)];

  if (unique.length === 0) return result;

  const rows = await sql`
    SELECT
      id,
      titulo AS title,
      autor_id AS "authorId"
    FROM livros
    WHERE id IN ${sql(unique)}
  ` as {
    id: number;
    title: string;
    authorId: number;
  }[];

  // Deletions are handled by ON DELETE CASCADE.
  if (!embedder || rows.length === 0) return result;

  result.created = await ensureBookIndex(embedder);

  const stored = await sql`
    SELECT
      livro_id AS id,
      texto
    FROM livros_vetores
    WHERE livro_id IN ${sql(rows.map((row) => row.id))}
  ` as {
    id: number;
    texto: string;
  }[];

  const storedTexts = new Map(
    stored.map((row) => [row.id, row.texto]),
  );

  const pending: { id: number; text: string }[] = [];

  for (const row of rows) {
    const author = await integration.author(sql, row.authorId);
    const text = indexText(row.title, author?.name);

    if (storedTexts.get(row.id) !== text) {
      pending.push({ id: row.id, text });
    }
  }

  if (pending.length === 0) return result;

  const vectors = await embedder.embed(
    pending.map((item) => item.text),
    "document",
  );

  if (vectors.length !== pending.length) {
    throw new Error("Embedder returned an unexpected number of vectors");
  }

  for (const [i, item] of pending.entries()) {
    const vector = vectors[i]!;

    if (vector.length !== embedder.dimensions) {
      throw new Error(
        `Expected ${embedder.dimensions} dimensions, received ${vector.length}`,
      );
    }

    await sql`
      INSERT INTO livros_vetores (
        livro_id,
        texto,
        embedding
      )
      VALUES (
        ${item.id},
        ${item.text},
        ${vectorToText(vector)}::vector
      )
      ON CONFLICT (livro_id) DO UPDATE
      SET
        texto = EXCLUDED.texto,
        embedding = EXCLUDED.embedding
    `;
  }

  result.indexed = pending.length;

  return result;
}

/**
 * Synchronizes books after their database transaction has committed.
 *
 * Never throws: if embedding fails, the book remains saved and can
 * be indexed during the next reconciliation.
 */
export async function syncBookIndex(
  ids: number[],
  integration: CatalogIntegration,
  embedder: Embedder | null = defaultEmbedder,
): Promise<IndexResult> {
  if (!embedder) {
    return { indexed: 0, removed: 0 };
  }

  try {
    const { created, ...result } = await syncIds(
      ids,
      integration,
      embedder,
    );

    // A newly created table needs vectors for the rest of the catalog too.
    if (created) {
      void reconcileBookIndex(integration, embedder);
    }

    return result;
  } catch (error) {
    console.warn(
      "Índice semântico indisponível:",
      (error as Error).message,
    );

    return { indexed: 0, removed: 0 };
  }
}

/**
 * Reconciles all books with the vector table.
 *
 * This covers books inserted directly through SQL (such as seed data)
 * and books whose indexed text changed while the embedder was unavailable.
 */
export async function reconcileBookIndex(
  integration: CatalogIntegration,
  embedder: Embedder | null = defaultEmbedder,
): Promise<IndexResult> {
  if (!embedder) {
    return { indexed: 0, removed: 0 };
  }

  try {
    // Also creates the table when the catalog is empty.
    await ensureBookIndex(embedder);

    const rows = await sql`
      SELECT id
      FROM livros
    ` as { id: number }[];

    const { created: _created, ...result } = await syncIds(
      rows.map((row) => row.id),
      integration,
      embedder,
    );

    return result;
  } catch (error) {
    console.warn(
      "Índice semântico indisponível:",
      (error as Error).message,
    );

    return { indexed: 0, removed: 0 };
  }
}

/** The author's name is part of the indexed text, so renaming reindexes their books. */
export async function syncAuthorBookIndex(
  authorId: number,
  integration: CatalogIntegration,
): Promise<void> {
  try {
    const rows = await sql`
      SELECT id
      FROM livros
      WHERE autor_id = ${authorId}
    ` as { id: number }[];

    await syncBookIndex(
      rows.map((row) => row.id),
      integration,
    );
  } catch (error) {
    console.warn(
      "Índice semântico indisponível:",
      (error as Error).message,
    );
  }
}

/** Finds the nearest books using cosine distance in PostgreSQL. */
export async function knnSearch(
  vector: Float32Array,
  limit: number,
): Promise<KnnHit[]> {
  const queryVector = vectorToText(vector);

  return await sql`
    SELECT
      livro_id AS id,
      embedding <=> ${queryVector}::vector AS distance
    FROM livros_vetores
    ORDER BY embedding <=> ${queryVector}::vector
    LIMIT ${limit}
  ` as KnnHit[];
}
